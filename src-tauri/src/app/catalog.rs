pub fn build_catalog(installed: &HashMap<String, InstalledRecord>) -> Vec<CatalogItem> {
    CATALOG_ENTRIES
        .iter()
        .map(|entry| {
            let found = installed
                .get(entry.id)
                .or_else(|| installed.get(&entry.id.to_lowercase()));
            let store_url = if entry.source == "msstore" {
                Some(format!("ms-windows-store://pdp/?ProductId={}", entry.id))
            } else {
                None
            };
            CatalogItem {
                id: entry.id.to_string(),
                name: entry.name.to_string(),
                source: entry.source.to_string(),
                category: entry.category.to_string(),
                summary: entry.summary.to_string(),
                publisher: entry.publisher.to_string(),
                tags: entry.tags.iter().map(|t| t.to_string()).collect(),
                popular: entry.popular,
                is_installed: found.is_some(),
                has_update: found.and_then(|r| r.available_version.as_ref()).is_some(),
                installed_version: found.map(|r| r.version.clone()),
                available_version: found.and_then(|r| r.available_version.clone()),
                store_url,
            }
        })
        .collect()
}
